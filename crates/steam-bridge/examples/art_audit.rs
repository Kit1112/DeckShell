//! Art audit (read-only): for every app in the live library compare what Steam's UI really loads for each asset
//! (walk of Steam's own URL list via fetch on steamloopback.host: URL + bytes + hash) with
//!   (a) LEGACY: the file-based lookup the app used before (steam-data: grid + librarycache guesses), and
//!   (b) NEW: steam-bridge ArtResolver (Steam's URL list -> local file).
//! Writes docs/art-audit.md. Run: cargo run --release -p steam-bridge --example art_audit [out.md]
use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::PathBuf;
use steam_bridge::art::fnv1a32_file;
use steam_bridge::*;

type Live = Option<(String, u64, u32)>;

fn same(live: &Live, local: Option<&PathBuf>) -> bool {
    match (live, local) {
        (None, None) => true,
        (Some((_, n, h)), Some(p)) => fnv1a32_file(p).map(|(ln, lh)| ln == *n && lh == *h).unwrap_or(false),
        _ => false,
    }
}

fn main() {
    let out = std::env::args().nth(1).unwrap_or_else(|| "docs/art-audit.md".into());
    let b = Bridge::connect().expect("steam not reachable");
    let root = steam_data::default_root().expect("steam root");
    let apps = b.apps().expect("apps");
    let ids: Vec<u32> = apps.iter().map(|a| a.appid).collect();
    let acct = b.active_account().expect("active account");
    let legacy = steam_data::load(&root).ok();
    let legacy_user = legacy.as_ref().and_then(|l| l.active_user);
    let by_id: std::collections::HashMap<u32, &steam_data::Game> = legacy.iter().flat_map(|l| l.games.iter().map(|g| (g.app_id, g))).collect();
    let cache = root.join("appcache/librarycache");
    let urls = b.art_urls(&ids).expect("art urls");
    let res = ArtResolver::new(&root, acct);
    let kinds = [ArtKind::Capsule, ArtKind::Header, ArtKind::Hero, ArtKind::Logo, ArtKind::Icon];

    let mut rows = String::new();
    let (mut total, mut mis_old, mut mis_new) = (0usize, 0usize, 0usize);
    let mut per_kind: BTreeMap<String, (usize, usize, usize)> = BTreeMap::new();
    let mut live_remote = 0usize;
    let mut anim = 0usize;
    let name: std::collections::HashMap<u32, &str> = apps.iter().map(|a| (a.appid, a.display_name.as_str())).collect();
    for u in &urls {
        let lists: Vec<&[String]> = kinds.iter().map(|k| u.list(*k)).collect();
        let live = b.art_fetch(&lists).unwrap_or_else(|e| panic!("fetch {}: {e}", u.appid));
        let new = res.resolve(u);
        let old = match by_id.get(&u.appid) {
            Some(g) => g.art.clone(),
            None => steam_data::art::librarycache(&cache, &u.appid.to_string()),
        };
        if new.capsule_animated.is_some() {
            anim += 1;
        }
        for (i, k) in kinds.iter().enumerate() {
            total += 1;
            let old_p = match k {
                ArtKind::Capsule => old.capsule.as_ref(),
                ArtKind::Header => old.header.as_ref(),
                ArtKind::Hero => old.hero.as_ref(),
                ArtKind::Logo => old.logo.as_ref(),
                ArtKind::Icon => old.icon.as_ref(),
            };
            let new_p = new.get(*k);
            if live[i].is_none() && u.list(*k).iter().any(|x| x.starts_with("http")) {
                live_remote += 1;
            }
            let (ok_old, ok_new) = (same(&live[i], old_p), same(&live[i], new_p));
            let e = per_kind.entry(format!("{k:?}")).or_default();
            e.0 += 1;
            if !ok_old { mis_old += 1; e.1 += 1; }
            if !ok_new { mis_new += 1; e.2 += 1; }
            if !ok_old || !ok_new {
                let _ = writeln!(rows, "| {} | {} | {:?} | {} | {} | {} |", u.appid, name.get(&u.appid).unwrap_or(&"?").replace('|', "/"),
                    k, live[i].as_ref().map(|l| l.0.split('?').next().unwrap().to_string()).unwrap_or_else(|| "-".into()),
                    if ok_old { "ok".into() } else { old_p.map(|p| p.strip_prefix(&root).unwrap_or(p).display().to_string()).unwrap_or_else(|| "none".into()) },
                    if ok_new { "ok".into() } else { new_p.map(|p| p.strip_prefix(&root).unwrap_or(p).display().to_string()).unwrap_or_else(|| "none".into()) });
            }
        }
    }
    let mut md = String::new();
    let _ = writeln!(md, "# Art audit\n\nGenerated by `crates/steam-bridge/examples/art_audit.rs` (read-only; `cargo run --release -p steam-bridge --example art_audit`).\n");
    let _ = writeln!(md, "Reference = what the live Big Picture <img> ends up loading: Steam's own URL list per asset (appStore/appDetailsStore, sp.js:341060, 435041-435140, 436674-436730), first URL answering 200 on steamloopback.host, compared by byte length + FNV-1a32 against the local file each implementation picks. `none == none` (Steam falls through to CDN/placeholder, we have no file either) counts as a match.\n");
    let _ = writeln!(md, "- Active account (bridge, friendStore.currentUserSteamID): **{acct}**; steam-data guess from loginusers.vdf: {:?}", legacy_user);
    let _ = writeln!(md, "- Apps audited: {} ({} asset slots); animated capsules among them: {anim}; assets where Steam itself falls through to a CDN download: {live_remote}", urls.len(), total);
    let _ = writeln!(md, "- **Mismatches LEGACY (file-based steam-data / librarycache guess): {mis_old}**");
    let _ = writeln!(md, "- **Mismatches NEW (Steam URL list -> steam-bridge ArtResolver): {mis_new}**\n");
    let _ = writeln!(md, "| asset | slots | legacy mismatches | new mismatches |\n|---|---|---|---|");
    for (k, (n, o, w)) in &per_kind {
        let _ = writeln!(md, "| {k} | {n} | {o} | {w} |");
    }
    let _ = writeln!(md, "\n## Mismatch rows (legacy or new)\n\n| appid | name | asset | Steam loads | legacy picks | new picks |\n|---|---|---|---|---|---|");
    md.push_str(&rows);
    std::fs::write(&out, md).expect("write report");
    println!("account={acct} apps={} slots={total} legacy_mismatch={mis_old} new_mismatch={mis_new} animated={anim} cdn_fallthrough={live_remote} -> {out}", urls.len());
}
