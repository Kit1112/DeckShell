#!/usr/bin/env python3
"""Regenerates app/src/screens/dejavu_advances.in (an expression for include!): advance widths (units of 1/2048 em) of DejaVu Sans, the fallback font of the Deck's
Gaming Mode UI (fontconfig), for the line-wrap estimate of the settings pages. Usage: dejavu_advances.py /usr/share/fonts/TTF/DejaVuSans.ttf OUT.rs"""
import sys
from fontTools.ttLib import TTFont
f = TTFont(sys.argv[1]); cm = f.getBestCmap(); h = f['hmtx']; assert f['head'].unitsPerEm == 2048
ranges = [(0x20, 0x7e), (0xa0, 0xff), (0x400, 0x45f), (0x490, 0x491), (0x2010, 0x2026), (0x2030, 0x203a), (0x2116, 0x2116), (0x2212, 0x2212)]
rows = [(c, h[cm[c]][0]) for a, b in ranges for c in range(a, b + 1) if c in cm]
with open(sys.argv[2], 'w') as o:
    o.write("// Generated by tools/extract-assets/dejavu_advances.py from DejaVu Sans (units per em 2048). Do not edit.\n")
    o.write("&[\n")
    for i in range(0, len(rows), 8):
        o.write("    " + " ".join(f"(0x{c:x},{a})," for c, a in rows[i:i + 8]) + "\n")
    o.write("]\n")
